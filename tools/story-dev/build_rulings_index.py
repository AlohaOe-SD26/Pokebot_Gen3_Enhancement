"""THE RULINGS INDEX (backlog N2, spec S3-2): a finding aid over `PROJECT KNOWLEDGE/06-DECISIONS-LOG.md`.

    06 WINS. The index is a finding aid; quote the section, never the table.

WHY. 06 is ~720 KB, append-only, with no index, and CLAUDE.md rule 11 says "grep 06 before escalating anything". About
ten `08` entries re-asked a question that 06 had already ruled on. Two things a grep cannot do are done here:
  * a STABLE id per section: `<date>-<sha1(heading text)[:6]>`. Not an ordinal (06 is `merge=union`, so two machines
    appending on the same day can reorder sections) and not the ruling number, which is NOT a key: USER RULING 12 and
    13 each name two DIFFERENT decisions (2026-09-23 and 2026-09-25), and other numbers repeat as applications or
    amendments. Line numbers are stored as a hint only.
  * the JUDGMENTS a parser cannot make live in a hand-curated overlay, `PROJECT KNOWLEDGE/rulings-overlay.json`:
    which do-not lines are real markers and which only QUOTE a rule, which repeated-number heading defines a ruling and
    which applies or amends one, what is superseded or withdrawn. THE GENERATOR CARRIES FACTS, THE OVERLAY JUDGMENT.
    A section absent from the overlay is ACTIVE with no flag, so an ordinary 06 append never forces an overlay edit.

OUTPUTS (both regenerated by running this file with no arguments):
  PROJECT KNOWLEDGE/RULINGS.generated.json   facts only (no overlay), one record per `## ` heading
  PROJECT KNOWLEDGE/RULINGS.md                 the human table: facts + the overlay's flags

`--check` (exit 1 on any failure, every failure listed):
  stale       a committed output differs from a fresh build (every 06 append does this; it prints the one command)
  unresolved  an overlay id resolves to no section (a renamed heading), or an overlay title disagrees with 06
  donot       a do-not CANDIDATE line (`do not re-raise`, `do not re-open`, `do-not-reopen`) is not classified
              `marker` or `mention` in the overlay
  repeat      a USER RULING number named in headings on two different dates, where a later heading carries neither
              `ruling_key`, `application_of` nor `amends` (USER RULING lists and ranges are expanded: "15-18")
  dangling    `superseded_by` / `application_of` / `amends` names no section; SUPERSEDED without `superseded_by`
  schema      an unknown overlay field, a bad status, a marker with no `do_not_reopen` line
  INFO (never fails): supersession-cue headings (correction, supersedes, withdrawn, replaced, re-affirmed, reversal)
  that have no overlay entry: the curation worklist.

`--repeats` prints every USER RULING number that headings name on more than one date, with each heading's overlay
relation (the source of the facts-ledger row about repeated numbers).

N1 NOTE: the section count here and `grep -c '^## '` use the SAME pattern, so comparing them is a DETERMINISM check,
not a recall control. Retrieval is measured by the golden queries in `selftest_rulings_index.py` (N6).

Run:  py -3.12 tools/story-dev/build_rulings_index.py            (regenerate)
      py -3.12 tools/story-dev/build_rulings_index.py --check    (gate)
Paths can be overridden (`--decisions`, `--overlay`, `--out-json`, `--out-md`) for tests; defaults derive from this
file's location, never from the current directory.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8")
    except (AttributeError, ValueError):
        pass

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
DOCS = REPO / "PROJECT KNOWLEDGE"
DEFAULT_DECISIONS = DOCS / "06-DECISIONS-LOG.md"
DEFAULT_OVERLAY = DOCS / "rulings-overlay.json"
DEFAULT_JSON = DOCS / "RULINGS.generated.json"
DEFAULT_MD = DOCS / "RULINGS.md"

READ_FIRST = "06 wins. This file is a finding aid; quote the section, never this table."
REGEN_CMD = "py -3.12 tools/story-dev/build_rulings_index.py"

#: ONE heading pattern, shared with the N1 grep (`^## `). A `### ` sub-heading is part of its section.
HEADING_RE = re.compile(r"^## (.*)$")
DATE_RE = re.compile(r"(\d{4}-\d{2}-\d{2})")
#: do-not CANDIDATE phrases: the spec's three (`do not re-raise`, `do not re-open`, `do-not-reopen`) plus
#: `do not re-ask`, which 06 uses for the same instruction (3 lines on 2026-10-21). `\s+` lets a phrase WRAP onto the
#: next line (2 such lines on 2026-10-21, invisible to a line grep); the candidate is the line where the phrase STARTS.
#: `do not re-propose` added the same day by the independent overlay review (06:4447, 4448 and 5661 use it for the same
#: instruction). A candidate is only a candidate: the overlay says marker (an instruction) or mention (a quotation of one).
DONOT_RE = re.compile(r"do\s+not\s+re-?(?:raise|open|ask|propose)|do-?not-?reopen", re.IGNORECASE)
#: supersession CUES in a heading. Word-bounded so "correctness", "self-correcting" and "REVERSIBLE" do not count.
CUE_RE = re.compile(
    r"\b(correction|corrections|corrects|supersedes|superseded|supersede|withdrawn|replaced|re-affirmed|"
    r"reversal|reversed|reversing)\b",
    re.IGNORECASE,
)
#: "USER RULING 12", "USER RULINGS 23, 24 and 25", "USER RULINGS 9 & 10", "USER RULINGS 15-18" (a range).
USER_RULING_RE = re.compile(
    r"USER RULINGS?\s+(\d+(?:\s*(?:,|&|\+|and|-|–)\s*\d+)*)", re.IGNORECASE
)
BARE_RULING_RE = re.compile(r"(?<!USER )\bRULINGS?\s+(\d+)", re.IGNORECASE)
SLUG_RE = re.compile(r"#\d+-[a-z0-9-]+")
KI_RE = re.compile(r"\bKI-\d+\b")

OVERLAY_FIELDS = {"title", "status", "superseded_by", "ruling_key", "application_of", "amends",
                  "do_not_reopen", "candidates", "topics", "reason"}
STATUSES = {"ACTIVE", "SUPERSEDED", "WITHDRAWN"}
CANDIDATE_CLASSES = {"marker", "mention"}
RULING_KEY_RE = re.compile(r"^\d+@\d{4}-\d{2}-\d{2}$")


# --------------------------------------------------------------------------------------------- parsing (facts)

def read_text(path: Path) -> str:
    """UTF-8, CRLF-tolerant: a Windows checkout (core.autocrlf=true) must index identically to an LF one."""
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def section_id(title: str) -> str:
    m = DATE_RE.search(title)
    date = m.group(1) if m else "undated"
    return f"{date}-{hashlib.sha1(title.encode('utf-8')).hexdigest()[:6]}"


def candidate_key(line: str) -> str:
    """A do-not candidate is keyed by its own text (not its line number, which an append can move)."""
    return hashlib.sha1(line.strip().encode("utf-8")).hexdigest()[:8]


def _expand_numbers(spec: str) -> list[int]:
    out: list[int] = []
    for a, b in re.findall(r"(\d+)\s*[-–]\s*(\d+)", spec):
        lo, hi = int(a), int(b)
        if lo < hi <= lo + 20:
            out.extend(range(lo, hi + 1))
    out.extend(int(n) for n in re.findall(r"\d+", spec))
    return sorted(set(out))


def ruling_numbers(title: str) -> list[int]:
    nums: set[int] = set()
    for m in USER_RULING_RE.finditer(title):
        nums.update(_expand_numbers(m.group(1)))
    return sorted(nums)


def parse_sections(text: str) -> list[dict]:
    """One record per `## ` heading, from the heading to the line before the next one (1-based line numbers)."""
    lines = text.split("\n")
    heads = [i for i, ln in enumerate(lines) if HEADING_RE.match(ln)]
    sections: list[dict] = []
    for k, i in enumerate(heads):
        end = heads[k + 1] if k + 1 < len(heads) else len(lines)
        while end - 1 > i and not lines[end - 1].strip():
            end -= 1
        title = HEADING_RE.match(lines[i]).group(1).strip()
        body_lines = lines[i + 1:end]
        body = "\n".join(body_lines)
        m = DATE_RE.search(title)
        rulings = ruling_numbers(title)
        bare = sorted({int(n) for n in BARE_RULING_RE.findall(title)} - set(rulings))
        donot = []
        for j, ln in enumerate(body_lines):
            nxt = body_lines[j + 1] if j + 1 < len(body_lines) else ""
            if any(m.start() < len(ln) for m in DONOT_RE.finditer(ln + " " + nxt)):
                text = ln.strip() if DONOT_RE.search(ln) else (ln.strip() + " " + nxt.strip())
                donot.append({"key": candidate_key(ln), "line": i + 2 + j, "text": text[:300]})
        sections.append({
            "id": section_id(title),
            "date": m.group(1) if m else "undated",
            "line_start": i + 1,
            "line_end": end,
            "title": title,
            "rulings": rulings,
            "ruling_mentions": bare,
            "slugs": sorted(set(SLUG_RE.findall(title + "\n" + body))),
            "ki": sorted(set(KI_RE.findall(title + "\n" + body)), key=lambda s: int(s[3:])),
            "donot": donot,
            "cues": sorted({c.lower() for c in CUE_RE.findall(title)}),
            "_body": body,
        })
    return sections


def facts_record(sections: list[dict], text: str) -> dict:
    return {
        "_READ_FIRST": READ_FIRST,
        "source": "PROJECT KNOWLEDGE/06-DECISIONS-LOG.md",
        "source_sha1_lf": hashlib.sha1(text.encode("utf-8")).hexdigest(),
        "regenerate": REGEN_CMD,
        "counts": {
            "sections": len(sections),
            "donot_candidates": sum(len(s["donot"]) for s in sections),
            "sections_naming_user_rulings": sum(1 for s in sections if s["rulings"]),
        },
        "sections": [{k: v for k, v in s.items() if not k.startswith("_")} for s in sections],
    }


# --------------------------------------------------------------------------------------------- overlay (judgment)

def load_overlay(path: Path | None) -> dict:
    if path is None or not path.is_file():
        return {}
    data = json.loads(read_text(path))
    return data.get("sections", {})


def repeated_numbers(sections: list[dict]) -> dict[int, list[dict]]:
    by_n: dict[int, list[dict]] = {}
    for s in sections:
        for n in s["rulings"]:
            by_n.setdefault(n, []).append(s)
    return {n: ss for n, ss in sorted(by_n.items()) if len({s["date"] for s in ss}) > 1}


# --- the guards: each is ONE function, called on ONE line of check() (the mutant harness deletes one call at a time)

def check_unique_ids(sections: list[dict], overlay: dict) -> list[str]:
    seen: dict[str, int] = {}
    out = []
    for s in sections:
        if s["id"] in seen:
            out.append(f"FAIL duplicate id {s['id']}: 06:{seen[s['id']]} and 06:{s['line_start']} have the same "
                       f"heading text; make one heading distinct (append a qualifier)")
        seen[s["id"]] = s["line_start"]
    return out


def check_overlay_resolves(sections: list[dict], overlay: dict) -> list[str]:
    by_id = {s["id"]: s for s in sections}
    out = []
    for oid, entry in overlay.items():
        if oid not in by_id:
            out.append(f"FAIL unresolved overlay id {oid} (title {entry.get('title', '?')[:80]!r}): no section has it "
                       f"(a renamed or deleted heading)")
        elif "title" in entry and entry["title"] != by_id[oid]["title"]:
            out.append(f"FAIL overlay title for {oid} disagrees with 06:{by_id[oid]['line_start']}")
    return out


def check_schema(sections: list[dict], overlay: dict) -> list[str]:
    out = []
    by_id = {s["id"]: s for s in sections}
    for oid, entry in overlay.items():
        extra = set(entry) - OVERLAY_FIELDS
        if extra:
            out.append(f"FAIL overlay {oid}: unknown field(s) {sorted(extra)}")
        if entry.get("status", "ACTIVE") not in STATUSES:
            out.append(f"FAIL overlay {oid}: status {entry.get('status')!r} not in {sorted(STATUSES)}")
        keys = entry.get("ruling_key")
        for k in ([keys] if isinstance(keys, str) else (keys or [])):
            if not RULING_KEY_RE.match(k):
                out.append(f"FAIL overlay {oid}: ruling_key {k!r} is not <n>@<YYYY-MM-DD>")
            elif oid in by_id and int(k.split("@")[0]) not in by_id[oid]["rulings"]:
                out.append(f"FAIL overlay {oid}: ruling_key {k!r} names a number its heading does not")
        cands = entry.get("candidates", {})
        for ck, cls in cands.items():
            if cls not in CANDIDATE_CLASSES:
                out.append(f"FAIL overlay {oid}: candidate {ck} class {cls!r} not marker/mention")
        if oid in by_id:
            live = {d["key"] for d in by_id[oid]["donot"]}
            for ck in cands:
                if ck not in live:
                    out.append(f"FAIL overlay {oid}: candidate {ck} matches no do-not line in the section (stale)")
        if any(c == "marker" for c in cands.values()) and not entry.get("do_not_reopen"):
            out.append(f"FAIL overlay {oid}: a candidate is a marker but the entry has no do_not_reopen line")
    return out


def check_donot_classified(sections: list[dict], overlay: dict) -> list[str]:
    out = []
    for s in sections:
        cands = overlay.get(s["id"], {}).get("candidates", {})
        for d in s["donot"]:
            if d["key"] not in cands:
                out.append(f"FAIL unclassified do-not 06:{d['line']} in {s['id']} ({s['title'][:70]}): "
                           f"key {d['key']} -> marker|mention :: {d['text'][:120]}")
    return out


def check_repeats(sections: list[dict], overlay: dict) -> list[str]:
    out = []
    for n, ss in repeated_numbers(sections).items():
        first = min(s["date"] for s in ss)
        firsts = ", ".join(f"06:{s['line_start']} {s['id']}" for s in ss if s["date"] == first)
        for s in ss:
            if s["date"] == first:
                continue
            e = overlay.get(s["id"], {})
            if not (e.get("ruling_key") or e.get("application_of") or e.get("amends")):
                out.append(f"FAIL repeated USER RULING {n}: 06:{s['line_start']} {s['id']} ({s['title'][:90]}) "
                           f"carries neither ruling_key, application_of nor amends; first named {first} at {firsts}")
    return out


def check_links(sections: list[dict], overlay: dict) -> list[str]:
    ids = {s["id"] for s in sections}
    out = []
    for oid, entry in overlay.items():
        for field in ("superseded_by", "application_of", "amends"):
            target = entry.get(field)
            for t in ([target] if isinstance(target, str) else (target or [])):
                if t not in ids:
                    out.append(f"FAIL dangling {field} in {oid}: {t} names no section")
        if entry.get("status") == "SUPERSEDED" and not entry.get("superseded_by"):
            out.append(f"FAIL overlay {oid}: SUPERSEDED without superseded_by")
    return out


def check_stale(fresh_json: str, fresh_md: str, out_json: Path, out_md: Path) -> list[str]:
    out = []
    for path, fresh in ((out_json, fresh_json), (out_md, fresh_md)):
        if not path.is_file():
            out.append(f"FAIL stale: {path.name} does not exist. Regenerate: {REGEN_CMD}")
        elif read_text(path) != fresh:
            out.append(f"FAIL stale: {path.name} differs from a fresh build of 06 + overlay. Regenerate: {REGEN_CMD}")
    return out


def info_cues(sections: list[dict], overlay: dict) -> list[str]:
    return [f"INFO cue heading not in overlay: 06:{s['line_start']} {s['id']} [{', '.join(s['cues'])}] "
            f"{s['title'][:110]}" for s in sections if s["cues"] and s["id"] not in overlay]


# --------------------------------------------------------------------------------------------- rendering

def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _ids(value) -> str:
    return ", ".join(f"`{v}`" for v in ([value] if isinstance(value, str) else value))


def render_json(facts: dict) -> str:
    return json.dumps(facts, ensure_ascii=False, indent=1) + "\n"


def render_md(sections: list[dict], overlay: dict) -> str:
    out = [f"> **{READ_FIRST}**", "",
           "# RULINGS index (generated from `06-DECISIONS-LOG.md`; never edit by hand)", "",
           f"- Regenerate: `{REGEN_CMD}` | gate: `{REGEN_CMD} --check`",
           "- Look up a question first: `py -3.12 tools/decomp_lookup.py ask \"<words>\"` (it quotes 06 itself).",
           "- Judgments (marker vs mention, supersession, which heading defines a repeated number) live in "
           "`rulings-overlay.json`; a section not in it is ACTIVE with no flag.",
           "- Line numbers are HINTS; the id `<date>-<sha1(heading)[:6]>` is the key.", ""]
    by_id = {s["id"]: s for s in sections}
    flagged = [s for s in sections if overlay.get(s["id"], {}).get("do_not_reopen")]
    out += ["## Do not reopen", "", "| id | 06 line | do not reopen |", "|---|---|---|"]
    for s in flagged:
        out.append(f"| `{s['id']}` | {s['line_start']} | {_cell(overlay[s['id']]['do_not_reopen'])} |")
    out += ["", "## Repeated USER RULING numbers (a number is not a key)", "",
            "| number | id | date | 06 line | relation |", "|---|---|---|---|---|"]
    for n, ss in repeated_numbers(sections).items():
        for s in ss:
            e = overlay.get(s["id"], {})
            rel = []
            if e.get("ruling_key"):
                k = e["ruling_key"]
                rel.append("defines " + (k if isinstance(k, str) else ", ".join(k)))
            if e.get("application_of"):
                rel.append("applies " + _ids(e["application_of"]))
            if e.get("amends"):
                rel.append("amends " + _ids(e["amends"]))
            out.append(f"| {n} | `{s['id']}` | {s['date']} | {s['line_start']} | {_cell('; '.join(rel) or '-')} |")
    out += ["", "## Superseded or withdrawn", "", "| id | 06 line | status | by | title |", "|---|---|---|---|---|"]
    for s in sections:
        e = overlay.get(s["id"], {})
        if e.get("status", "ACTIVE") != "ACTIVE":
            out.append(f"| `{s['id']}` | {s['line_start']} | {e['status']} | `{e.get('superseded_by', '-')}` | "
                       f"{_cell(s['title'][:140])} |")
    out += ["", f"## All {len(sections)} sections (newest first)", "",
            "| id | 06 line | user rulings | flags | title |", "|---|---|---|---|---|"]
    for s in reversed(sections):
        e = overlay.get(s["id"], {})
        flags = []
        if e.get("do_not_reopen"):
            flags.append("DO-NOT-REOPEN")
        if e.get("status", "ACTIVE") != "ACTIVE":
            flags.append(e["status"])
        if s["cues"]:
            flags.append("cue")
        out.append(f"| `{s['id']}` | {s['line_start']} | {', '.join(map(str, s['rulings'])) or ''} | "
                   f"{' '.join(flags)} | {_cell(s['title'][:160])} |")
    del by_id
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------------------------- entry points

def build(decisions: Path, overlay_path: Path | None) -> tuple[list[dict], dict, str, str]:
    text = read_text(decisions)
    sections = parse_sections(text)
    overlay = load_overlay(overlay_path)
    return sections, overlay, render_json(facts_record(sections, text)), render_md(sections, overlay)


def check(decisions: Path, overlay_path: Path | None, out_json: Path, out_md: Path) -> tuple[list[str], list[str]]:
    sections, overlay, fresh_json, fresh_md = build(decisions, overlay_path)
    problems: list[str] = []
    problems += check_unique_ids(sections, overlay)
    problems += check_overlay_resolves(sections, overlay)
    problems += check_schema(sections, overlay)
    problems += check_donot_classified(sections, overlay)
    problems += check_repeats(sections, overlay)
    problems += check_links(sections, overlay)
    problems += check_stale(fresh_json, fresh_md, out_json, out_md)
    return problems, info_cues(sections, overlay)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--decisions", type=Path, default=DEFAULT_DECISIONS)
    ap.add_argument("--overlay", type=Path, default=DEFAULT_OVERLAY)
    ap.add_argument("--out-json", type=Path, default=DEFAULT_JSON)
    ap.add_argument("--out-md", type=Path, default=DEFAULT_MD)
    ap.add_argument("--check", action="store_true", help="gate: exit 1 on any failure; writes nothing")
    ap.add_argument("--repeats", action="store_true", help="print repeated USER RULING numbers and exit")
    args = ap.parse_args(argv)

    if args.repeats:
        sections, overlay, _, _ = build(args.decisions, args.overlay)
        for n, ss in repeated_numbers(sections).items():
            print(f"USER RULING {n}: named in headings on {len({s['date'] for s in ss})} dates")
            for s in ss:
                e = overlay.get(s["id"], {})
                rel = "; ".join(
                    ([f"defines {e['ruling_key']}"] if e.get("ruling_key") else []) +
                    ([f"applies {e['application_of']}"] if e.get("application_of") else []) +
                    ([f"amends {e['amends']}"] if e.get("amends") else [])) or "UNCLASSIFIED"
                print(f"   06:{s['line_start']:<5} {s['id']}  {rel}  :: {s['title'][:100]}")
        return 0

    if args.check:
        problems, infos = check(args.decisions, args.overlay, args.out_json, args.out_md)
        sections = parse_sections(read_text(args.decisions))
        for line in problems + infos:
            print(line)
        n_cand = sum(len(s["donot"]) for s in sections)
        if problems:
            print(f"RULINGS INDEX CHECK FAILED: {len(problems)} problem(s); {len(sections)} sections, "
                  f"{n_cand} do-not candidates, {len(infos)} cue heading(s) not reviewed")
            return 1
        print(f"RULINGS INDEX CHECK OK: {len(sections)} sections, {n_cand} do-not candidates classified, "
              f"{len(infos)} cue heading(s) not reviewed (INFO)")
        return 0

    _, _, fresh_json, fresh_md = build(args.decisions, args.overlay)
    for path, text in ((args.out_json, fresh_json), (args.out_md, fresh_md)):
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
