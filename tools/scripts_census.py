"""The census of every line in the game's event scripts at the PINNED decomp (KB2 slice 2's first prerequisite).

WHY: the slice-2 design (`items_gifts.json`, `events.json`; `ai-research-notes/2026-10-19-BUILD-SPECS-step-3.md`, the
"NEEDS DESIGN" block) may not write a parser before "a census of every distinct `scripts.inc` command with its count on
the pinned clone, written down". A parser built on the shapes someone remembers misses the shapes nobody remembered;
this counts every line instead, and REFUSES to call the census complete while any line is unclassified.

Every non-blank line of `data/maps/*/scripts.inc` (and, as a second table, the shared `data/scripts/*.inc`) is one of:
  comment    starts with `@` (the assembler's comment character), or a ONE-line C comment `/* ... */`
  preproc    a C preprocessor line (`#ifdef BUGFIX`, `#else`, `#endif`, ...): the vanilla ROM is built WITHOUT `BUGFIX`
             and `UBFIX`, so a parser must keep the `#ifndef` / `#else` side of each such block; every one is LISTED
  label      `Name::` or `Name:` (a script, text or movement entry point)
  directive  starts with `.` (`.byte`, `.2byte`, `.string`, ...): data, not a command
  command    starts with a lowercase identifier: a script or movement MACRO; its first token is what is counted
  UNPARSED   anything else: the census exits 1 and names each such line (file:line), so a new shape is seen at once

Usage:
  py -3.12 tools/scripts_census.py                   the census at the pin, printed as markdown (exit 0 = no UNPARSED)
  py -3.12 tools/scripts_census.py --out FILE.md     the same, written to FILE.md
  py -3.12 tools/scripts_census.py --self-test       a CONTROL (a clean fake tree: 0 UNPARSED) and a FAULT (one planted
                                                     unparsable line: exit 1 naming it), on a temp tree; no decomp needed
The decomp is found and pin-checked by `tools/decomp_lookup.py` (`--decomp`, env POKEBOT_DECOMP, or the sibling
`../_decomp/pokeemerald`); a clone at another commit is REFUSED (exit 2). Read-only.
"""
from __future__ import annotations

import argparse
import re
import sys
import tempfile
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))
import decomp_lookup as dl  # noqa: E402  (one pin check for every decomp reader)

LABEL = re.compile(r"[A-Za-z_][A-Za-z0-9_]*::?(\s*@.*)?")
DIRECTIVE = re.compile(r"\.[A-Za-z0-9_]+\b")
COMMAND = re.compile(r"([a-z_][a-z0-9_]*)\b")
GROUPS = (("map scripts", "data/maps/*/scripts.inc"), ("shared scripts", "data/scripts/*.inc"))


def classify(line: str) -> tuple[str, str | None]:
    """(kind, the counted token) for one stripped, non-blank line."""
    if line.startswith("@") or (line.startswith("/*") and line.endswith("*/")):
        return "comment", None
    if line.startswith("#"):
        return "preproc", line.split()[0]
    if LABEL.fullmatch(line):
        return "label", None
    m = DIRECTIVE.match(line)
    if m:
        return "directive", m.group(0)
    m = COMMAND.match(line)
    if m:
        return "command", m.group(1)
    return "UNPARSED", None


def census(root: Path, pattern: str) -> dict:
    files = sorted(root.glob(pattern))
    kinds: Counter = Counter()
    commands: Counter = Counter()
    directives: Counter = Counter()
    command_files: dict[str, set] = defaultdict(set)
    unparsed: list[str] = []
    preproc: list[str] = []
    for f in files:
        rel = f.relative_to(root).as_posix()
        for n, raw in enumerate(dl.read_lines(f), 1):
            line = raw.strip()
            if not line:
                continue
            kind, token = classify(line)
            kinds[kind] += 1
            if kind == "command":
                commands[token] += 1
                command_files[token].add(rel)
            elif kind == "directive":
                directives[token] += 1
            elif kind == "preproc":
                preproc.append(f"{rel}:{n}: {line[:100]}")
            elif kind == "UNPARSED":
                unparsed.append(f"{rel}:{n}: {line[:100]}")
    return {"files": len(files), "kinds": kinds, "commands": commands, "directives": directives,
            "command_files": command_files, "unparsed": unparsed, "preproc": preproc}


def render(root: Path, pin: str, results: list[tuple[str, str, dict]]) -> str:
    out = [f"# Event-script census at the pinned decomp `{pin[:8]}`",
           "",
           "> GENERATED by `py -3.12 tools/scripts_census.py --out <this file>`; do not edit by hand. Every non-blank line "
           "is a comment, a label, a directive (`.byte`, `.string`, ...) or a command (a lowercase script or movement "
           "macro, counted by its first token); anything else is UNPARSED and fails the census.",
           ""]
    for title, pattern, r in results:
        k = r["kinds"]
        out += [f"## {title} (`{pattern}`): {r['files']} files",
                "",
                f"- lines: {sum(k.values())} non-blank = {k['command']} commands + {k['label']} labels + "
                f"{k['directive']} directives + {k['comment']} comments + {k['preproc']} preprocessor + "
                f"**{k['UNPARSED']} UNPARSED**",
                f"- distinct commands: {len(r['commands'])}; distinct directives: {len(r['directives'])}",
                ""]
        if r["unparsed"]:
            out += ["UNPARSED lines:", ""] + [f"- `{u}`" for u in r["unparsed"]] + [""]
        if r["preproc"]:
            out += ["Preprocessor lines (the vanilla ROM is built without `BUGFIX`/`UBFIX`: a parser keeps the "
                    "`#ifndef` / `#else` side):", ""] + [f"- `{p}`" for p in r["preproc"]] + [""]
        out += ["| command | lines | files |", "|---|---:|---:|"]
        for name, count in sorted(r["commands"].items(), key=lambda kv: (-kv[1], kv[0])):
            out.append(f"| `{name}` | {count} | {len(r['command_files'][name])} |")
        out += ["", "| directive | lines |", "|---|---:|"]
        for name, count in sorted(r["directives"].items(), key=lambda kv: (-kv[1], kv[0])):
            out.append(f"| `{name}` | {count} |")
        out.append("")
    return "\n".join(out)


def verdict(results: list[tuple[str, str, dict]]) -> int:
    """The exit code: 1 while any line of any table is UNPARSED (the census is then incomplete), else 0."""
    return 1 if any(r["unparsed"] for _, _, r in results) else 0


def self_test() -> int:
    ok = True
    with tempfile.TemporaryDirectory(prefix="scripts_census_") as tmp:
        root = Path(tmp)
        (root / "data" / "maps" / "TestTown").mkdir(parents=True)
        good = ("TestTown_MapScripts::\n\tmap_script MAP_SCRIPT_ON_TRANSITION, TestTown_OnTransition\n\t.byte 0\n\n"
                "@ a comment\nTestTown_OnTransition:\n\tsetflag FLAG_TEST\n#ifdef BUGFIX\n\tgiveitem ITEM_POTION\n"
                "#endif\n/* never used */\n\tend\n")
        f = root / "data" / "maps" / "TestTown" / "scripts.inc"
        f.write_text(good, encoding="utf-8")
        r = census(root, GROUPS[0][1])
        control = (not r["unparsed"] and r["commands"] == Counter({"map_script": 1, "setflag": 1, "giveitem": 1, "end": 1})
                   and r["kinds"]["label"] == 2 and r["kinds"]["directive"] == 1 and r["kinds"]["comment"] == 2
                   and len(r["preproc"]) == 2 and r["preproc"][0].startswith("data/maps/TestTown/scripts.inc:8:"))
        print(("PASS" if control else "FAIL") + "  CONTROL: a clean tree counts 4 commands, 2 labels, 1 directive, "
              "2 comments, 2 preprocessor lines LISTED by file:line, and 0 UNPARSED")
        control &= verdict([("t", GROUPS[0][1], r)]) == 0
        ok &= control
        f.write_text(good + "\t\"a stray string\"\n", encoding="utf-8")
        r = census(root, GROUPS[0][1])
        fault = (len(r["unparsed"]) == 1 and r["unparsed"][0].startswith("data/maps/TestTown/scripts.inc:13:")
                 and verdict([("t", GROUPS[0][1], r)]) == 1)
        print(("PASS" if fault else "FAIL") + "  FAULT: one planted unparsable line is reported by file:line and "
              f"turns the verdict to exit 1 ({r['unparsed']})")
        ok &= fault
    print("SELFTEST scripts_census: " + ("ALL PASS" if ok else "FAILED"))
    return 0 if ok else 1


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--decomp", type=Path, help="the decomp clone (default: POKEBOT_DECOMP or ../_decomp/pokeemerald)")
    ap.add_argument("--out", type=Path, help="write the markdown census here instead of printing it")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        return self_test()
    try:
        root = dl.decomp_root(args.decomp)
    except dl.DecompRefused as exc:
        print(dl.refusal_text(exc))
        return 2
    pin = dl.read_pin()
    results = [(title, pattern, census(root, pattern)) for title, pattern in GROUPS]
    text = render(root, pin, results)
    if args.out:
        args.out.write_text(text + "\n", encoding="utf-8", newline="\n")
        print(f"wrote {args.out}")
    else:
        print(text)
    for title, _, r in results:
        print(f"CENSUS {title}: {r['files']} files, {sum(r['kinds'].values())} lines, {len(r['commands'])} distinct "
              f"commands, {len(r['unparsed'])} UNPARSED", file=sys.stderr)
    return verdict(results)


if __name__ == "__main__":
    raise SystemExit(main())
